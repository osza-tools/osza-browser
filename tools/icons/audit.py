#!/usr/bin/env python3
# ============================================================
# Osza - icon and resource auditor
#
# Static audit of every way artwork reaches the screen:
#
#   1. themed icon names requested by code / theme CSS
#      but not provided by a bundled (resource) icon theme
#   2. qrc entries whose files do not exist on disk
#   3. resource paths (":/..." and "qrc:...") referenced in
#      code, UI files, CSS, HTML or JS that no .qrc provides
#   4. asset files that exist on disk but are referenced
#      nowhere (not registered, or registered but unused)
#   5. SVGs that fail to render
#
# The SVG render check uses cairosvg as a stand-in for Qt's
# SVG renderer (the generated assets are intentionally kept
# inside the QtSvg subset: paths, basic shapes, gradients,
# clip paths, opacity - no filters, masks or <text>).
#
# Usage:
#   python3 tools/icons/audit.py                 # human report
#   python3 tools/icons/audit.py --json          # machine report
#   python3 tools/icons/audit.py --strict        # exit 1 on any finding
#
# Copyright (C) 2026 Osza Tools contributors
# GPL-3.0-or-later
# ============================================================

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Dict, Iterable, List, Set

try:
    import cairosvg  # type: ignore
except ImportError:  # pragma: no cover
    cairosvg = None

REPO = Path(__file__).resolve().parents[2]

SCAN_SUFFIXES = {
    ".cpp", ".h", ".ui", ".css", ".js", ".html", ".qml", ".qrc", ".pl",
    ".py", ".sh", ".desktop", ".json", ".metainfo.xml", ".xml", ".txt",
}
SCAN_DIRS = [
    REPO / "src",
    REPO / "themes",
    REPO / "linux",
    REPO / "mac",
    REPO / "tests",
    REPO / "CMakeLists.txt",
]
SKIP_PARTS = {"3rdparty", "po", "poqm", ".git"}

# Packaging art consumed by external projects (NSIS/DMG scripts, distro
# packages) that reference the files by path rather than from the repo text.
# Regenerated by tools/icons/build.py - listed here so the auditor does not
# flag them as orphans.
PACKAGING_ASSETS = {
    "src/lib/data/icons/exeicons/osza.ico",
    "src/lib/data/icons/exeicons/osza.icns",
    "src/lib/data/icons/exeicons/page.ico",
    "src/lib/data/icons/exeicons/page16.png",
    "src/lib/data/icons/exeicons/page256.png",
    "src/lib/data/icons/exeicons/page32.png",
    "src/lib/data/icons/exeicons/page48.png",
}

# Qt module resources referenced by the code but provided by Qt itself at
# runtime, not by our .qrc files.
EXTERNAL_RESOURCES = {
    "/qtwebchannel/qwebchannel.js",  # shipped inside the QtWebChannel plugin
}

# Resource roots that are icon/art payloads we audit for orphans.
ASSET_DIRS = [
    REPO / "src/lib/data/icons",
    REPO / "src/lib/data/html",
    REPO / "src/plugins",
    REPO / "src/lib/adblock/data",
    REPO / "src/scripts/runaction/actions",
    REPO / "themes",
]

# --- regexes ---------------------------------------------------------------

# QIcon::fromTheme(QSL("name") / QStringLiteral("name") / "name"
RE_THEMED_CPP = re.compile(
    r'''fromTheme\s*\(\s*(?:QSL|QStringLiteral|QLatin1String)?\s*\(?\s*["']([a-z0-9][a-z0-9-]*)["']'''
)
# qproperty-themeIcon: "name";
RE_THEMED_CSS = re.compile(r'qproperty-themeIcon:\s*"?([a-z0-9-]+)"?')
# <iconset theme="name">
RE_THEMED_UI = re.compile(r'<iconset\s+theme="([a-z0-9-]+)"')

# :/path and :path resource references (Qt also accepts ":icons/x.svg"
# without the leading slash). We require a file-ish extension and refuse a
# letter/digit right before the ':' so URLs ("https://...") and C++ comments
# never match.
RES_SUFFIX = (".svg", ".png", ".gif", ".ico", ".icns", ".qml", ".js", ".css",
              ".html", ".json", ".txt", ".mp3", ".mp4", ".db", ".ini", ".ttf")
RE_RES_COLON = re.compile(
    r'''(?<![A-Za-z0-9]):(/[A-Za-z0-9_@][A-Za-z0-9_@./-]*\.[A-Za-z0-9]+)'''
)
RE_RES_QRC = re.compile(r'''qrc:(/?[A-Za-z0-9_@][A-Za-z0-9_@./-]*\.[A-Za-z0-9]+)''')
# url(images/..) inside theme css (resolved relative to the css file)
RE_CSS_URL = re.compile(r'''url\(\s*["']?([^"'()]+)["']?\s*\)''')

RE_QRC_FILE = re.compile(r"<file([^>]*)>([^<]+)</file>")


def iter_repo_files() -> Iterable[Path]:
    seen: Set[Path] = set()
    for scan_dir in SCAN_DIRS:
        paths = [scan_dir] if scan_dir.is_file() else (
            sorted(scan_dir.rglob("*")) if scan_dir.exists() else []
        )
        for path in paths:
            if not path.is_file():
                continue
            if path.suffix not in SCAN_SUFFIXES and path.name not in ("CMakeLists.txt", "README"):
                continue
            if any(part in SKIP_PARTS for part in path.parts):
                continue
            rp = path.resolve()
            if rp in seen:
                continue
            seen.add(rp)
            yield path


def repo_relative(path: Path) -> str:
    try:
        return path.resolve().relative_to(REPO).as_posix()
    except ValueError:
        return str(path)


# --- qrc parsing -----------------------------------------------------------

def parse_qrc(qrc: Path) -> Dict[str, Path]:
    """Return mapping resource-path -> on-disk file for one .qrc file."""
    text = qrc.read_text(encoding="utf-8", errors="replace")
    resources: Dict[str, Path] = {}
    pos = 0
    prefix = ""
    for m in re.finditer(r'<qresource\s+([^>]*)>|</qresource>', text):
        if m.group(0).startswith("</"):
            continue
        prefix = (re.search(r'prefix="([^"]*)"', m.group(1) or "") or [None, ""])[1]
        block_start = m.end()
        block_end = text.find("</qresource>", block_start)
        block = text[block_start:block_end if block_end != -1 else len(text)]
        for fm in RE_QRC_FILE.finditer(block):
            attrs, name = fm.group(1), fm.group(2).strip()
            am = re.search(r'alias="([^"]+)"', attrs)
            target = am.group(1) if am else name
            res = ("/" + prefix.strip("/") + "/" + target).replace("//", "/")
            res = "/" + res.lstrip("/")
            resources[res] = (qrc.parent / name).resolve()
    if "<qresource>" in text and not resources:
        for fm in RE_QRC_FILE.finditer(text):
            name = fm.group(2).strip()
            resources["/" + name] = (qrc.parent / name).resolve()
    return resources


def collect_resources() -> Dict[str, Path]:
    resources: Dict[str, Path] = {}
    for qrc in REPO.rglob("*.qrc"):
        if any(part in SKIP_PARTS for part in qrc.parts):
            continue
        resources.update(parse_qrc(qrc))
    return resources


# --- bundled icon themes ----------------------------------------------------

def bundled_themes(resources: Dict[str, Path]) -> Dict[str, Path]:
    """Theme name -> directory of every index.theme shipped in resources."""
    themes: Dict[str, Path] = {}
    for res, disk in resources.items():
        parts = res.split("/")
        if len(parts) == 3 and parts[0] == "" and parts[1] == "icons" and parts[2] == "index.theme":
            themes[Path(str(disk)).parent.name] = Path(str(disk)).parent
        elif len(parts) >= 3 and parts[-1] == "index.theme" and parts[1] == "icons":
            themes[parts[-2]] = Path(str(disk)).parent
    return themes


def theme_index_dirs(theme_dir: Path) -> List[str]:
    index = theme_dir / "index.theme"
    if not index.exists():
        return []
    text = index.read_text(encoding="utf-8", errors="replace")
    m = re.search(r"^\s*Directories\s*=\s*(.+)$", text, re.MULTILINE)
    if not m:
        return []
    return [d for d in re.split(r"[, ]+", m.group(1).strip()) if d]


def theme_provides(theme_dir: Path) -> Set[str]:
    names: Set[str] = set()
    for d in theme_index_dirs(theme_dir):
        size_dir = theme_dir / d
        if not size_dir.is_dir():
            continue
        for f in size_dir.iterdir():
            if f.is_file():
                names.add(f.stem)
    return names


# --- the audit ---------------------------------------------------------------

def find_themed_names(files: Iterable[Path]) -> Dict[str, List[str]]:
    """name -> sorted list of request sites."""
    hits: Dict[str, Set[str]] = {}
    for path in files:
        text = path.read_text(encoding="utf-8", errors="replace")
        names: Set[str] = set()
        names.update(RE_THEMED_CPP.findall(text))
        names.update(RE_THEMED_UI.findall(text))
        if path.suffix == ".css":
            names.update(RE_THEMED_CSS.findall(text))
        for name in names:
            for i, line in enumerate(text.splitlines(), 1):
                if name in line:
                    hits.setdefault(name, set()).add(f"{repo_relative(path)}:{i}")
    return {name: sorted(sites) for name, sites in sorted(hits.items())}


def find_resource_refs(files: Iterable[Path]) -> Dict[str, List[str]]:
    refs: Dict[str, Set[str]] = {}
    for path in files:
        text = path.read_text(encoding="utf-8", errors="replace")
        for res in RE_RES_QRC.findall(text):
            res = "/" + res.lstrip("/")
            refs.setdefault(res, set()).add(repo_relative(path))
        for res in RE_RES_COLON.findall(text):
            if not res.endswith(RES_SUFFIX):
                continue
            refs.setdefault(res, set()).add(repo_relative(path))
    return {res: sorted(sites) for res, sites in sorted(refs.items())}


def check_svgs(files: Iterable[Path]) -> List[str]:
    if cairosvg is None:
        return ["(cairosvg unavailable - render check skipped)"]
    bad: List[str] = []
    for path in files:
        if path.suffix != ".svg":
            continue
        try:
            cairosvg.svg2png(url=str(path), output_width=32, output_height=32)
        except Exception as exc:  # noqa: BLE001
            bad.append(f"{repo_relative(path)}: {type(exc).__name__}: {exc}")
    return bad


def audit() -> dict:
    files = list(iter_repo_files())
    resources = collect_resources()
    themes = bundled_themes(resources)

    # 1. themed names requested vs provided
    requested = find_themed_names(files)
    provided: Set[str] = set()
    for theme_dir in themes.values():
        provided |= theme_provides(theme_dir)
    missing_themed = {n: sites for n, sites in requested.items() if n not in provided}

    # 2. qrc entries whose files are missing
    qrc_missing = sorted(
        f"{res} -> {repo_relative(disk)}"
        for res, disk in resources.items()
        if not disk.exists()
    )

    # 3. referenced resource paths that no qrc provides
    refs = find_resource_refs(files)
    unresolved = {}
    for res, sites in refs.items():
        if res in EXTERNAL_RESOURCES:
            continue
        if res not in resources:
            unresolved[res] = sites

    # theme css url() targets: disk-relative refs must exist on disk,
    # qrc:/: refs must resolve through the qrc map
    css_missing = []
    for path in files:
        if path.suffix != ".css":
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        for rel in RE_CSS_URL.findall(text):
            rel = rel.split("?")[0].split("#")[0]
            if rel.startswith("%"):
                rel = rel.replace("%23", "#").split("#")[0]
            if not rel or rel.startswith(("data:", "#")):
                continue
            if rel.startswith(("qrc:", ":")):
                res = "/" + rel.split(":", 1)[1].lstrip("/")
                if res not in resources:
                    css_missing.append(f"{repo_relative(path)}: url({rel})")
            elif not (path.parent / rel).exists():
                css_missing.append(f"{repo_relative(path)}: url({rel})")

    # 4. orphaned assets (on disk, referenced by neither qrc nor any source text)
    registered_files: Set[Path] = {p for p in resources.values() if p.exists()}
    referenced_text = "\n".join(
        p.read_text(encoding="utf-8", errors="replace") for p in files
    )
    orphans: List[str] = []
    for asset_dir in ASSET_DIRS:
        if not asset_dir.exists():
            continue
        for path in sorted(asset_dir.rglob("*")):
            if not path.is_file():
                continue
            if path.suffix not in {".svg", ".png", ".gif", ".ico", ".icns", ".jpg", ".webp"}:
                continue
            if "copyright" in path.name or "license" in path.name.lower():
                continue
            in_qrc = path.resolve() in registered_files
            mentioned = path.name in referenced_text
            if repo_relative(path) in PACKAGING_ASSETS:
                continue  # consumed by external packaging projects, see below
            if not in_qrc and not mentioned:
                orphans.append(repo_relative(path))

    # 5. svg render check
    svg_bad = check_svgs(
        p for d in ASSET_DIRS for p in sorted(d.rglob("*.svg")) if d.exists()
    )

    return {
        "themes_bundled": {name: repo_relative(d) for name, d in sorted(themes.items())},
        "themed_names_requested": len(requested),
        "themed_names_provided": sorted(provided),
        "missing_themed_names": missing_themed,
        "qrc_entries_missing_files": qrc_missing,
        "resource_refs_unresolved": unresolved,
        "theme_css_missing_images": css_missing,
        "orphaned_assets": orphans,
        "svg_render_failures": svg_bad,
    }


def print_report(result: dict) -> None:
    def section(title: str, items) -> None:
        print(f"\n== {title} ({len(items)}) ==")
        if isinstance(items, dict):
            for key, val in items.items():
                where = val if isinstance(val, list) else [val]
                extra = f" +{len(where)-1} more" if len(where) > 1 else ""
                print(f"  {key}  [{where[0]}{extra}]")
        else:
            for item in items:
                print(f"  {item}")

    print("Osza icon/resource audit")
    print(f"  bundled themes: {', '.join(result['themes_bundled']) or '(none)'}")
    print(f"  distinct themed names requested: {result['themed_names_requested']}")
    print(f"  distinct themed names provided:  {len(result['themed_names_provided'])}")

    section("Themed names requested but NOT provided", result["missing_themed_names"])
    section(".qrc entries whose file is missing on disk", result["qrc_entries_missing_files"])
    section("Resource references that no .qrc resolves", result["resource_refs_unresolved"])
    section("Theme CSS url() images missing on disk", result["theme_css_missing_images"])
    section("Asset files referenced nowhere (orphans)", result["orphaned_assets"])
    section("SVGs that fail to render", result["svg_render_failures"])
    print("")


def main() -> int:
    ap = argparse.ArgumentParser(description="Osza icon/resource auditor")
    ap.add_argument("--json", action="store_true", help="emit JSON")
    ap.add_argument("--strict", action="store_true", help="exit 1 on any finding")
    ap.add_argument("-o", "--output", type=Path, help="also write report to file")
    args = ap.parse_args()

    result = audit()

    if args.json:
        out = json.dumps(result, indent=2, sort_keys=True)
    else:
        import io
        from contextlib import redirect_stdout
        buf = io.StringIO()
        with redirect_stdout(buf):
            print_report(result)
        out = buf.getvalue()
    sys.stdout.write(out)
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(out, encoding="utf-8")

    if args.strict:
        problems = sum(
            len(result[k]) if isinstance(result[k], (list, dict)) else 0
            for k in (
                "missing_themed_names",
                "qrc_entries_missing_files",
                "resource_refs_unresolved",
                "theme_css_missing_images",
                "svg_render_failures",
            )
        )
        return 1 if problems else 0
    return 0


if __name__ == "__main__":
    sys.exit(main())
